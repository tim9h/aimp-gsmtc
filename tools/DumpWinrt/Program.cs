// Generates src/winrt_decls.h (WinRT ABI interface declarations) from the system .winmd metadata.
// Usage: dotnet run --project tools/DumpWinrt -- <output header>
using System.Collections.Immutable;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Security.Cryptography;
using System.Text;

var winmdDir = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.Windows), "System32", "WinMetadata");
var db = new Db(Directory.GetFiles(winmdDir, "*.winmd"));

string[] interfaces =
{
    "Windows.Media.ISystemMediaTransportControls",
    "Windows.Media.ISystemMediaTransportControls2",
    "Windows.Media.ISystemMediaTransportControlsDisplayUpdater",
    "Windows.Media.IMusicDisplayProperties",
    "Windows.Media.IMusicDisplayProperties2",
    "Windows.Media.ISystemMediaTransportControlsTimelineProperties",
    "Windows.Media.ISystemMediaTransportControlsButtonPressedEventArgs",
    "Windows.Media.IPlaybackPositionChangeRequestedEventArgs",
    "Windows.Storage.Streams.IRandomAccessStreamReference",
    "Windows.Storage.Streams.IRandomAccessStreamReferenceStatics",
    "Windows.Storage.Streams.IRandomAccessStream",
};

string[] enums =
{
    "Windows.Media.MediaPlaybackStatus",
    "Windows.Media.MediaPlaybackType",
    "Windows.Media.SystemMediaTransportControlsButton",
};

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated> by tools/DumpWinrt from %WINDIR%\\System32\\WinMetadata. Do not edit. </auto-generated>");
sb.AppendLine("#pragma once");
sb.AppendLine("#include <windows.h>");
sb.AppendLine("#include <inspectable.h>");
sb.AppendLine("#include <hstring.h>");
sb.AppendLine();
sb.AppendLine("namespace winrt_abi {");
sb.AppendLine();
sb.AppendLine("typedef INT64 EventRegistrationToken;");
sb.AppendLine("struct TimeSpan { INT64 Duration; };");
sb.AppendLine("struct DateTime { INT64 UniversalTime; };");
sb.AppendLine();

foreach (var e in enums)
{
    var t = db.FindType(e);
    sb.AppendLine($"enum {t.Name} : INT32 {{");
    foreach (var f in t.Fields)
        sb.AppendLine($"    {t.Name}_{f.Name} = {f.Constant},");
    sb.AppendLine("};");
    sb.AppendLine();
}

foreach (var name in interfaces)
{
    var t = db.FindType(name);
    sb.AppendLine($"struct {t.Name};");
}
sb.AppendLine();

foreach (var name in interfaces)
{
    var t = db.FindType(name);
    sb.AppendLine($"static const GUID IID_{t.Name} = {GuidInit(t.Guid)}; // {t.FullName}");
}
sb.AppendLine();

var handlerIids = new SortedDictionary<string, Guid>();

foreach (var name in interfaces)
{
    var t = db.FindType(name);
    sb.AppendLine($"struct {t.Name} : public IInspectable {{");
    foreach (var m in t.Methods)
    {
        var sig = m.Signature;
        var ps = new List<string>();
        for (int i = 0; i < sig.Params.Count; i++)
        {
            var (ty, byRef) = sig.Params[i];
            var pname = m.ParamNames.Count > i ? m.ParamNames[i] : $"p{i}";
            ps.Add($"{Abi(ty, db)}{(byRef ? "*" : "")} {pname}");
        }
        if (sig.Return != "void")
            ps.Add($"{Abi(sig.Return, db)}* result");
        sb.AppendLine($"    virtual HRESULT STDMETHODCALLTYPE {m.Name}({string.Join(", ", ps)}) = 0;");

        if (m.Name.StartsWith("add_") && db.IsGenericInst(sig.Params[0].Type))
            handlerIids[m.Name.Substring(4) + "Handler"] = db.PinterfaceIid(sig.Params[0].Type);
    }
    sb.AppendLine("};");
    sb.AppendLine();
}

foreach (var kv in handlerIids)
    sb.AppendLine($"static const GUID IID_{kv.Key} = {GuidInit(kv.Value)};");
sb.AppendLine();
sb.AppendLine("static const wchar_t RuntimeClass_RandomAccessStreamReference[] = L\"Windows.Storage.Streams.RandomAccessStreamReference\";");
sb.AppendLine();
sb.AppendLine("} // namespace winrt_abi");

var outPath = args.Length > 0 ? args[0] : "winrt_decls.h";
File.WriteAllText(outPath, sb.ToString());
Console.WriteLine($"Wrote {outPath}");

static string GuidInit(Guid g)
{
    var b = g.ToByteArray();
    uint d1 = BitConverter.ToUInt32(b, 0);
    ushort d2 = BitConverter.ToUInt16(b, 4), d3 = BitConverter.ToUInt16(b, 6);
    return $"{{0x{d1:x8}, 0x{d2:x4}, 0x{d3:x4}, {{{string.Join(", ", b.Skip(8).Select(x => $"0x{x:x2}"))}}}}}";
}

static string Abi(string sig, Db db) => sig switch
{
    "bool" => "BOOLEAN",
    "string" => "HSTRING",
    "i4" => "INT32",
    "u4" => "UINT32",
    "i8" => "INT64",
    "u8" => "UINT64",
    "r4" => "float",
    "r8" => "double",
    "u1" => "BYTE",
    "char" => "wchar_t",
    "void" => "void",
    _ => db.AbiOfNamed(sig),
};

record MethodSig(List<(string Type, bool ByRef)> Params, string Return);
record MethodInfoX(string Name, MethodSig Signature, List<string> ParamNames);
record FieldInfoX(string Name, object Constant);

class TypeInfoX
{
    public string Name, FullName;
    public Guid Guid;
    public List<MethodInfoX> Methods = new();
    public List<FieldInfoX> Fields = new();
}

class Db
{
    readonly List<MetadataReader> _modules = new();

    public Db(IEnumerable<string> files)
    {
        foreach (var f in files)
        {
            var pe = new PEReader(File.OpenRead(f));
            _modules.Add(pe.GetMetadataReader());
        }
    }

    public bool IsGenericInst(string sig) => sig.StartsWith("<");

    (MetadataReader R, TypeDefinition T)? Find(string fullName)
    {
        foreach (var r in _modules)
            foreach (var h in r.TypeDefinitions)
            {
                var t = r.GetTypeDefinition(h);
                if (FullName(r, t) == fullName) return (r, t);
            }
        return null;
    }

    static string FullName(MetadataReader r, TypeDefinition t) =>
        r.GetString(t.Namespace) + "." + r.GetString(t.Name);

    static string BaseName(MetadataReader r, TypeDefinition t) =>
        !t.BaseType.IsNil && t.BaseType.Kind == HandleKind.TypeReference
            ? r.GetString(r.GetTypeReference((TypeReferenceHandle)t.BaseType).Name) : "";

    public static Guid ReadGuid(MetadataReader r, TypeDefinition t)
    {
        foreach (var ah in t.GetCustomAttributes())
        {
            var a = r.GetCustomAttribute(ah);
            if (a.Constructor.Kind != HandleKind.MemberReference) continue;
            var mr = r.GetMemberReference((MemberReferenceHandle)a.Constructor);
            if (mr.Parent.Kind != HandleKind.TypeReference) continue;
            var tr = r.GetTypeReference((TypeReferenceHandle)mr.Parent);
            if (r.GetString(tr.Name) != "GuidAttribute") continue;
            var b = r.GetBlobBytes(a.Value);
            return new Guid(BitConverter.ToUInt32(b, 2), BitConverter.ToUInt16(b, 6), BitConverter.ToUInt16(b, 8),
                b[10], b[11], b[12], b[13], b[14], b[15], b[16], b[17]);
        }
        throw new Exception("no guid on " + FullName(r, t));
    }

    public TypeInfoX FindType(string fullName)
    {
        var (r, t) = Find(fullName) ?? throw new Exception("type not found: " + fullName);
        var info = new TypeInfoX { Name = r.GetString(t.Name), FullName = fullName };
        bool isEnum = BaseName(r, t) == "Enum";
        if (!isEnum && (t.Attributes & System.Reflection.TypeAttributes.Interface) != 0)
            info.Guid = ReadGuid(r, t);

        var provider = new SigProvider(this, r);
        foreach (var mh in t.GetMethods())
        {
            var m = r.GetMethodDefinition(mh);
            var sig = m.DecodeSignature(provider, null);
            var names = new List<string>();
            foreach (var ph in m.GetParameters())
            {
                var p = r.GetParameter(ph);
                if (p.SequenceNumber == 0) continue;
                names.Add(r.GetString(p.Name));
            }
            var ps = new List<(string, bool)>();
            foreach (var pt in sig.ParameterTypes)
            {
                bool byRef = pt.EndsWith("&");
                ps.Add((byRef ? pt[..^1] : pt, byRef));
            }
            info.Methods.Add(new MethodInfoX(r.GetString(m.Name), new MethodSig(ps, sig.ReturnType), names));
        }
        foreach (var fh in t.GetFields())
        {
            var fd = r.GetFieldDefinition(fh);
            var cn = fd.GetDefaultValue();
            if (cn.IsNil) continue;
            var cv = r.GetConstant(cn);
            var rd = r.GetBlobReader(cv.Value);
            object val = cv.TypeCode switch
            {
                ConstantTypeCode.Int32 => rd.ReadInt32(),
                ConstantTypeCode.UInt32 => (int)rd.ReadUInt32(),
                _ => throw new Exception("enum type"),
            };
            info.Fields.Add(new FieldInfoX(r.GetString(fd.Name), val));
        }
        return info;
    }

    static readonly HashSet<string> known = new()
    {
        "Windows.Media.ISystemMediaTransportControls",
        "Windows.Media.ISystemMediaTransportControlsDisplayUpdater",
        "Windows.Media.IMusicDisplayProperties",
        "Windows.Media.ISystemMediaTransportControlsTimelineProperties",
        "Windows.Storage.Streams.IRandomAccessStreamReference",
    };

    public string AbiOfNamed(string sig)
    {
        if (sig == "C:System.TimeSpan" || sig.StartsWith("V:Windows.Foundation.TimeSpan")) return "TimeSpan";
        if (sig == "C:System.DateTimeOffset" || sig.StartsWith("V:Windows.Foundation.DateTime")) return "DateTime";
        if (sig == "C:System.Runtime.InteropServices.WindowsRuntime.EventRegistrationToken") return "EventRegistrationToken";
        if (sig.StartsWith("E:")) return "INT32";
        if (sig.StartsWith("C:"))
        {
            var n = sig[2..];
            var def = DefaultInterfaceName(n) ?? n;
            return known.Contains(def) ? def[(def.LastIndexOf('.') + 1)..] + "*" : "IInspectable*";
        }
        return "void*";
    }

    string DefaultInterfaceName(string n)
    {
        var f = Find(n);
        if (f == null) return null;
        var (r, t) = f.Value;
        if ((t.Attributes & System.Reflection.TypeAttributes.Interface) != 0) return n;
        foreach (var ih in t.GetInterfaceImplementations())
        {
            var ii = r.GetInterfaceImplementation(ih);
            foreach (var ah in ii.GetCustomAttributes())
            {
                var a = r.GetCustomAttribute(ah);
                var mr = r.GetMemberReference((MemberReferenceHandle)a.Constructor);
                var tr = r.GetTypeReference((TypeReferenceHandle)mr.Parent);
                if (r.GetString(tr.Name) == "DefaultAttribute")
                    return SigProvider.NameOfHandle(this, r, ii.Interface)[2..];
            }
        }
        return null;
    }

    // pinterface IID: UUIDv5 over the WinRT type signature, in the WinRT parameterized-type namespace.
    public Guid PinterfaceIid(string genericSig)
    {
        var s = SignatureOf(genericSig);
        var ns = new Guid("11f47ad5-7b73-42c0-abae-878b1e16adee").ToByteArray();
        SwapGuid(ns);
        var hash = SHA1.HashData(ns.Concat(Encoding.UTF8.GetBytes(s)).ToArray());
        var g = hash.Take(16).ToArray();
        g[6] = (byte)((g[6] & 0x0F) | 0x50);
        g[8] = (byte)((g[8] & 0x3F) | 0x80);
        SwapGuid(g);
        return new Guid(g);
    }

    static void SwapGuid(byte[] b)
    {
        (b[0], b[3]) = (b[3], b[0]);
        (b[1], b[2]) = (b[2], b[1]);
        (b[4], b[5]) = (b[5], b[4]);
        (b[6], b[7]) = (b[7], b[6]);
    }

    string SignatureOf(string sig)
    {
        if (sig.StartsWith("<"))
        {
            var parts = SplitTop(sig[1..^1]);
            var (gr, gt) = Find(parts[0]) ?? throw new Exception("generic not found " + parts[0]);
            return $"pinterface({{{ReadGuid(gr, gt)}}};{string.Join(";", parts.Skip(1).Select(SignatureOf))})";
        }
        if (sig.StartsWith("C:"))
        {
            var n = sig[2..];
            var (r, t) = Find(n) ?? throw new Exception("not found " + n);
            if ((t.Attributes & System.Reflection.TypeAttributes.Interface) != 0)
                return $"{{{ReadGuid(r, t)}}}";
            foreach (var ih in t.GetInterfaceImplementations())
            {
                var ii = r.GetInterfaceImplementation(ih);
                foreach (var ah in ii.GetCustomAttributes())
                {
                    var a = r.GetCustomAttribute(ah);
                    var mr = r.GetMemberReference((MemberReferenceHandle)a.Constructor);
                    var tr = r.GetTypeReference((TypeReferenceHandle)mr.Parent);
                    if (r.GetString(tr.Name) == "DefaultAttribute")
                        return $"rc({n};{SignatureOf(SigProvider.NameOfHandle(this, r, ii.Interface))})";
                }
            }
            throw new Exception("no default interface for " + n);
        }
        throw new Exception("unsupported signature " + sig);
    }

    static List<string> SplitTop(string s)
    {
        var res = new List<string>();
        int depth = 0, start = 0;
        for (int i = 0; i < s.Length; i++)
        {
            if (s[i] == '<') depth++;
            else if (s[i] == '>') depth--;
            else if (s[i] == ';' && depth == 0) { res.Add(s[start..i]); start = i + 1; }
        }
        res.Add(s[start..]);
        return res;
    }

    public string KindOfRef(MetadataReader r, TypeReferenceHandle h)
    {
        var tr = r.GetTypeReference(h);
        var full = r.GetString(tr.Namespace) + "." + r.GetString(tr.Name);
        var f = Find(full);
        return f == null ? "C:" + full : KindOf(f.Value.R, f.Value.T, full);
    }

    public string KindOf(MetadataReader r, TypeDefinition t, string full)
    {
        var bt = BaseName(r, t);
        if (bt == "Enum") return "E:" + full;
        if (bt == "ValueType") return "V:" + full;
        return "C:" + full;
    }
}

class SigProvider : ISignatureTypeProvider<string, object>
{
    readonly Db _db; readonly MetadataReader _r;
    public SigProvider(Db db, MetadataReader r) { _db = db; _r = r; }

    public static string NameOfHandle(Db db, MetadataReader r, EntityHandle h)
    {
        switch (h.Kind)
        {
            case HandleKind.TypeReference: return db.KindOfRef(r, (TypeReferenceHandle)h);
            case HandleKind.TypeDefinition:
                var t = r.GetTypeDefinition((TypeDefinitionHandle)h);
                return db.KindOf(r, t, r.GetString(t.Namespace) + "." + r.GetString(t.Name));
            case HandleKind.TypeSpecification:
                return r.GetTypeSpecification((TypeSpecificationHandle)h).DecodeSignature(new SigProvider(db, r), null);
        }
        throw new Exception("handle " + h.Kind);
    }

    public string GetPrimitiveType(PrimitiveTypeCode c) => c switch
    {
        PrimitiveTypeCode.Boolean => "bool",
        PrimitiveTypeCode.String => "string",
        PrimitiveTypeCode.Int32 => "i4",
        PrimitiveTypeCode.UInt32 => "u4",
        PrimitiveTypeCode.Int64 => "i8",
        PrimitiveTypeCode.UInt64 => "u8",
        PrimitiveTypeCode.Single => "r4",
        PrimitiveTypeCode.Double => "r8",
        PrimitiveTypeCode.Byte => "u1",
        PrimitiveTypeCode.Char => "char",
        PrimitiveTypeCode.Void => "void",
        _ => c.ToString(),
    };
    public string GetTypeFromDefinition(MetadataReader reader, TypeDefinitionHandle handle, byte k) => NameOfHandle(_db, reader, handle);
    public string GetTypeFromReference(MetadataReader reader, TypeReferenceHandle handle, byte k) => NameOfHandle(_db, reader, handle);
    public string GetTypeFromSpecification(MetadataReader reader, object ctx, TypeSpecificationHandle handle, byte k) => NameOfHandle(_db, reader, handle);
    public string GetGenericInstantiation(string generic, ImmutableArray<string> args)
        => "<" + generic[2..] + ";" + string.Join(";", args) + ">";
    public string GetByReferenceType(string e) => e + "&";
    public string GetSZArrayType(string e) => "array";
    public string GetArrayType(string e, ArrayShape s) => "array";
    public string GetPointerType(string e) => "ptr";
    public string GetFunctionPointerType(MethodSignature<string> s) => "fnptr";
    public string GetGenericMethodParameter(object c, int i) => "!!" + i;
    public string GetGenericTypeParameter(object c, int i) => "!" + i;
    public string GetModifiedType(string m, string u, bool r) => u;
    public string GetPinnedType(string e) => e;
}



